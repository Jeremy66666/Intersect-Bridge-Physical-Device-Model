            if (ramanProcess->state() != QProcess::NotRunning) { ramanOutput->append("[Already running]"); return; }
            if (backendCaptureFault) { ramanOutput->append("[Scan] Capture fault: confirm Laser OFF, close and restart the app before a new run."); return; }
            currentScanMode = mode;
            sessionId = QUuid::createUuid().toString(QUuid::WithoutBraces);
            const QString root = QCoreApplication::applicationDirPath() + "/scan_sessions";
            const QString label = mode == "1d-x" ? "1d_x_scan" : mode == "1d-y" ? "1d_y_scan" : "2d_scan";

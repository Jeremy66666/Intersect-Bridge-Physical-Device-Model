    bool collectRamanData(const QString& captureId, QVector<int>& spectrum, QString& error, bool preview = false) {
        const QString base = laserProcess->workingDirectory();
        if (backendCaptureFault || laserProcess->state() != QProcess::Running) {
            error = "Backend unavailable/faulted"; return false;
        }
        // Never overwrite an unconsumed command or reuse an identifier.
        if (QFile::exists(base + "/command.txt") ||
            !AcquisitionProtocol::publish(base + "/command.txt", ((preview ? "M " : "S ") + captureId + "\n").toUtf8())) {
            error = "Backend command pending or write failed"; backendCaptureFault = true; return false;
        }
        QElapsedTimer elapsed; elapsed.start();
#ifdef HANDSHAKE_TESTING
        const int captureTimeoutMs = 1500;
#else
        const int captureTimeoutMs = 15000;
#endif
        const int maxReadAttempts = 3;
        const int readRetryDelayMs = 100;
        int readAttempts = 0;
        qint64 nextReadAt = 0;
        QString lastReadError;
        while (elapsed.elapsed() < captureTimeoutMs) {
            QCoreApplication::processEvents(QEventLoop::AllEvents, 10);
            if (preview && !monitorReply.isEmpty()) {
                if (!AcquisitionProtocol::parseSpectrum(monitorReply, captureId, kNumPixels, spectrum, error)) break;
                return true;
            }
            QFile result(base + "/capture_results/" + captureId + ".txt");
            if (!preview && result.exists() && elapsed.elapsed() >= nextReadAt) {
                ++readAttempts;
                QByteArray contents;
                const bool opened = result.open(QIODevice::ReadOnly);
                if (opened) contents = result.readAll();
                if (!opened || result.error() != QFileDevice::NoError) {
                    lastReadError = QString("Cannot read capture result (attempt %1/%2): %3; file: %4")
                        .arg(readAttempts).arg(maxReadAttempts).arg(result.errorString(), result.fileName());
                    result.close();
                    appendLaserLog("[Capture read] " + lastReadError);
                    if (readAttempts >= maxReadAttempts) { error = lastReadError; break; }
                    // Retry only this file, never send another acquisition command.
                    nextReadAt = elapsed.elapsed() + readRetryDelayMs;
                } else {
                    result.close();
                    if (!AcquisitionProtocol::parseSpectrum(contents, captureId, kNumPixels, spectrum, error)) break;
                    if (readAttempts > 1)
                        appendLaserLog(QString("[Capture read recovered] %1; attempt %2/%3")
                            .arg(captureId).arg(readAttempts).arg(maxReadAttempts));
                    return true;
                }
            }
            if (laserProcess->state() != QProcess::Running) { error = "Backend exited during capture"; break; }
            QThread::msleep(20);
        }
        if (error.isEmpty()) error = QString("Capture timed out (%1 ms); no blind retry and no success ACK").arg(captureTimeoutMs)
            + (lastReadError.isEmpty() ? QString() : "; " + lastReadError);
        backendCaptureFault = true;
        return false;
    }

    void handleScanPoint() {
        if (isCollecting || laserCommandBusy || !scanActive || scanCancelled ||
            !laserOn || ramanProcess->state() != QProcess::Running) return;
        QFile request(sessionDir + "/request.txt");
        if (!request.open(QIODevice::ReadOnly)) return;
        AcquisitionProtocol::Point point;
        const auto bytes = request.readAll(); request.close();
        if (!AcquisitionProtocol::parsePoint(bytes, sessionId, point)) {
            failScan("Invalid point request or wrong session"); return;
        }
        if (point.id != lastCompletedPoint && point.id != lastCompletedPoint + 1) {
            failScan("Unexpected point sequence"); return;
        }
        if (paused) {
            if (!replyToPoint(point.id, "PAUSED")) failScan("Cannot publish pause heartbeat");
            return;
        }
        if (point.id == lastCompletedPoint) {
            if (!replyToPoint(point.id, "OK")) failScan("Cannot publish saved-point ACK");
            return;
        }
        QScopedValueRollback<bool> captureGuard(isCollecting, true);
        if (!replyToPoint(point.id, "HOLD")) { failScan("Cannot publish capture heartbeat"); return; }
        const QString captureId = sessionId + "_" + QString::number(point.id);
        const QString started = QDateTime::currentDateTimeUtc().toString(Qt::ISODateWithMs);
        QElapsedTimer duration; duration.start();
        QVector<int> spectrum; QString error;
        if (!collectRamanData(captureId, spectrum, error)) {
            replyToPoint(point.id, "FAIL"); failScan(error); return;
        }
        if (scanCancelled || !scanActive || ramanProcess->state() != QProcess::Running) {
            appendLaserLog("[Capture discarded from scan] Scan stopped; raw backend result retained: " + captureId);
            return;
        }
        QJsonArray pixels;
        for (int value : spectrum) pixels.append(value);
        QJsonObject record{
            {"scan_mode", currentScanMode},
            {"protocol", 2}, {"session_id", sessionId}, {"point_id", static_cast<qint64>(point.id)},
            {"capture_id", captureId}, {"started_utc", started},
            {"completed_utc", QDateTime::currentDateTimeUtc().toString(Qt::ISODateWithMs)},
            {"capture_elapsed_ms", duration.elapsed()}, {"status", "OK"},
            {"controller_x_steps", point.x}, {"controller_y_steps", point.y}, {"controller_z_steps", point.z},
            {"pixel_count", spectrum.size()}, {"intensity", pixels}
        };
        const QString file = sessionDir + QString("/point_%1.json").arg(point.id, 4, 10, QChar('0'));
        if (!AcquisitionProtocol::publish(file, QJsonDocument(record).toJson())) {
            replyToPoint(point.id, "FAIL"); failScan("Cannot save point spectrum"); return;
        }
        // Keep the legacy hexadecimal Image Data line for existing TXT readers.
        QString txt;
        QTextStream out(&txt);
        out << "# Scan mode: " << currentScanMode << "\n# Session: " << sessionId
            << "\n# Point: " << point.id << "\n# Completed UTC: " << record["completed_utc"].toString()
            << "\n# Controller XYZ steps: " << point.x << " " << point.y << " " << point.z
            << "\n# Pixels: " << spectrum.size() << "\nImage Data";
        for (int value : spectrum) out << " " << QString::number(value, 16).toUpper().rightJustified(4, '0');
        out << "\n";
        out.flush();
        // Atomically replace the combined log before acknowledging this point.
        const QString combinedPath = sessionDir + "/laser_log_combined.txt";
        QByteArray combined = combinedScanTxt;
        combined += txt.toUtf8();
        combined += "Stop Capture\n\n";
        if (!AcquisitionProtocol::publish(combinedPath, combined)) {
            replyToPoint(point.id, "FAIL"); failScan("Cannot save combined TXT; point not acknowledged"); return;
        }
        combinedScanTxt = combined;
        lastCompletedPoint = point.id;
        displaySpectrum(spectrum);
        rtChart->setTitle(QString("%1 - saved point %2%3 (LIVE)").arg(currentScanMode).arg(point.id)
                         .arg(currentScanMode == "2d" ? "" : "/13"));
        appendLaserLog(QString("[Point saved] run=%1 point=%2 pixels=%3 elapsed_ms=%4")
                       .arg(sessionId).arg(point.id).arg(spectrum.size()).arg(duration.elapsed()));
        // Pause during exposure saves this point but holds the motor until Resume.
        if (!replyToPoint(point.id, paused ? "PAUSED" : "OK")) failScan("Cannot publish point ACK");
    }

    // Hamamatsu SampleApl menu: 6 -> USB2_setLDPowerEnable; 4 -> USB2_setLDPower;
    // 5 -> USB2_getLDPowerEnable. Each setter consumes its parameter separately.
    bool setLaserEnabledAndConfirm(bool enable) {
        const QString ackFile = "command_completed.txt";
        laserReplyBuffer.clear();
        if (!sendLaserCommand("6", ackFile) ||
            !sendLaserCommand(enable ? "1" : "0", ackFile)) return false;
        if (enable) {
            if (!sendLaserCommand("4", ackFile) ||
                !sendLaserCommand(powerCommandForLevel(selectedPower), ackFile)) return false;
        }
        // The file acknowledges command consumption, not USB success. Read back
        // enable state from the device before permitting a scan.
        if (!sendLaserCommand("5", ackFile)) return false;
        const QRegularExpression statePattern("LD Power Enable\\s*:\\s*0x([0-9a-fA-F]+)");
        QElapsedTimer timer;
        timer.start();
        while (timer.elapsed() < 4000) {
            QCoreApplication::processEvents();
            if (laserProcess->state() != QProcess::Running ||
                laserReplyBuffer.contains("Error code", Qt::CaseInsensitive)) return false;
            const auto match = statePattern.match(laserReplyBuffer);
            if (match.hasMatch()) {
                bool ok = false;
                const auto actual = match.captured(1).toUInt(&ok, 16);
                return ok && ((actual == 1) == enable);
            }
            QThread::msleep(20);
        }
        appendLaserLog("[Laser] Timed out reading LD Power Enable from backend.");
        return false;
    }

    bool sendLaserCommand(const QString &cmd, const QString &ackFileName = "command_completed.txt") {
        const QString basePath = laserProcess->workingDirectory();
        QString commandFilePath = basePath + "/command.txt";
        QString completedFilePath = basePath + "/" + ackFileName;
        QFile completedFile(completedFilePath);
        if (completedFile.exists()) completedFile.remove();
        if (QFile::exists(commandFilePath) || !AcquisitionProtocol::publish(commandFilePath, cmd.toUtf8())) {
            appendLaserLog("[Error] Pending backend command or command write failed."); return false;
        }
        QElapsedTimer timer; timer.start();
        while (timer.elapsed() < 4000) {
            QCoreApplication::processEvents();
            if (QFile::exists(completedFilePath)) {
                QFile doneFile(completedFilePath);
                if (doneFile.open(QIODevice::ReadOnly | QIODevice::Text)) {
                    QString response = doneFile.readAll(); doneFile.close();
                    if (response.contains("done")) { QFile::remove(completedFilePath); return true; }
                }
            }
            QThread::msleep(100);
        }
        appendLaserLog("[Timeout waiting for command processing]");
        return false;
    }

    QVector<QPointF> spectrumToShiftCurve_RT(const QVector<int>& intensity) {
        QVector<QPointF> pts; int n = intensity.size();
        if (n < 10) return pts;
        int maxPoints = std::min(n, kNumPixels); pts.reserve(maxPoints);
        for (int i = 0; i < maxPoints; ++i) pts.append(QPointF(kRamanShift[i], intensity[i]));
        return pts;
    }

    bool readLastImageDataHexAsInts_RT(const QString& path, QVector<int>& out) {
        QFile file(path); if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) return false;
        QTextStream in(&file); QString lastLine;
        while (!in.atEnd()) { const QString line = in.readLine(); if (line.contains("Image Data")) lastLine = line; }
        file.close(); if (lastLine.isEmpty()) return false;
        const int idx = lastLine.indexOf("Image Data");
        QStringList hexList = lastLine.mid(idx + int(strlen("Image Data"))).split(" ", Qt::SkipEmptyParts);
        out.clear(); out.reserve(hexList.size());
        for (const QString& hex : hexList) { bool ok = false; int value = hex.toInt(&ok, 16); if (ok) out.push_back(value); }
        return !out.isEmpty();
    }

    bool parseImageDataLineToInts(const QString& line, QVector<int>& out) const {
        const int idx = line.indexOf("Image Data"); if (idx < 0) return false;
        QStringList hexList = line.mid(idx + int(strlen("Image Data"))).split(" ", Qt::SkipEmptyParts);
        out.clear(); out.reserve(hexList.size());
        for (const QString& hex : hexList) { bool ok = false; int value = hex.toInt(&ok, 16); if (ok) out.push_back(value); }
        return !out.isEmpty();
    }

    QString saveDarkMeasurementToTxt(const QVector<int>& spectrum) const {
        const QString dir = QCoreApplication::applicationDirPath() + "/dark_measurements";
        if (!QDir().mkpath(dir)) return QString();
        const QString base = dir + QString("/dark_%1").arg(QDateTime::currentDateTime().toString("yyyyMMdd_HHmmss_zzz"));
        QString path = base + ".txt";
        for (int suffix = 1; QFile::exists(path); ++suffix) path = base + "_" + QString::number(suffix) + ".txt";
        QFile file(path); if (!file.open(QIODevice::WriteOnly | QIODevice::Text | QIODevice::NewOnly)) return QString();
        QTextStream out(&file);
        out << "# Dark Measurement\n# Timestamp: " << QDateTime::currentDateTime().toString("yyyy-MM-dd HH:mm:ss.zzz")
            << "\n# Points: " << spectrum.size() << "\nindex\traman_shift_cm-1\tintensity\n";
        const int n = std::min<int>(static_cast<int>(spectrum.size()), kNumPixels);
        for (int i = 0; i < n; ++i) out << i << "\t" << QString::number(kRamanShift[i], 'f', 8) << "\t" << spectrum[i] << "\n";
        out.flush();
        const bool saved = out.status() == QTextStream::Ok && file.flush();
        file.close();
        if (!saved) { file.remove(); return QString(); }
        return path;
    }

